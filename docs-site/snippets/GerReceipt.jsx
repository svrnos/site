// Eventually moves into the DB (ger_codes.evidence_checklist, ger_codes.regulatory_mappings)
// — but for v0.2 launch this is the hard-coded fallback so the receipt works
// even on codes that haven't had their per-code metadata authored yet.
//
// Defaults (used when a code has no specific entry) keep the receipt useful
// rather than blank.
// ---------------------------------------------------------------------------

