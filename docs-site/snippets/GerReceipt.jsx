// Diagnostic Receipt — the structured-evidence output you take to a regulator,
// insurer, vendor, or class-action attorney when filing an AI-incident claim.
//
// Built per the NotebookLM deterministic redesign: 4 fixed sections, no AI,
// pure logic. Inputs: one or more GER codes (selected by the user from the
// lookup tool). Output: a printable / markdown-exportable document.
// ============================================================================

// Mintlify provides React hooks (useState/useMemo) globally — no import needed.
import gerData from "../data/ger.json";

const codes = gerData.codes;
const codeMap = new Map(codes.map((c) => [c.code, c]));

// ---------------------------------------------------------------------------
